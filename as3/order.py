#!/usr/bin/env python3
"""order.py: write all.as including classes.txt's files with base classes first."""
import re, os
files = [l.strip() for l in open('classes.txt') if l.strip() and not l.startswith('#')]
name_of = {os.path.basename(f)[:-3]: f for f in files}
deps = {}
for f in files:
    s = open(f, encoding='utf-8').read()
    m = re.search(r'class\s+\w+\s+extends\s+([\w.]+)', s)
    deps[f] = []
    if m:
        b = m.group(1).split('.')[-1]
        if b in name_of: deps[f].append(name_of[b])
out, seen = [], set()
def visit(f):
    if f in seen: return
    seen.add(f)
    for d in deps[f]: visit(d)
    out.append(f)
for f in files: visit(f)
open('all.as', 'w').write('// FLASHNT built-in ActionScript 3 classes (generated by order.py from classes.txt)\n' + ''.join('include "%s"\n' % f for f in out))
