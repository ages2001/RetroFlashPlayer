static V2 snd_loadPCM(VM2 *vm, V2 self, int argc, V2 *argv) {
    A2Obj *o = SELFO, *ba; A2Sound *s = snd_of(o); u32 samples, i, avail; int is_float = 1, stereo = 1, ch, k, bps; double rate = 44100; SoundDef *sd;
    if (!s) return v2_undef();
    if (s->state == SS_LOADED) return v2_undef();
    if (ARG(0).t != T_OBJ || ARG(0).u.o->kind != OK_BYTEARRAY) { a2_throw_error(vm, "TypeError", "Error #2007: Parameter bytes must be non-null.", 2007); return v2_undef(); }
    ba = ARG(0).u.o; samples = v2_touint(vm, ARG(1));
    if (argc > 2 && ARG(2).t != T_UNDEF) { A2Str *f = v2_tostr(vm, ARG(2)); is_float = strcmp(f->s, "short") != 0; }
    if (argc > 3) stereo = v2_tobool(vm, ARG(3));
    if (argc > 4) rate = v2_tonum(vm, ARG(4));
    if (!(rate >= 1) || rate > 1000000) rate = 44100;
    ch = stereo ? 2 : 1; bps = is_float ? 4 : 2;
    avail = ba->bpos >= 0 && ba->bpos < ba->blen ? (u32)(ba->blen - ba->bpos) / (u32)(bps * ch) : 0;
    if (samples > avail) samples = avail;
    sd = (SoundDef*)calloc(1, sizeof(SoundDef));
    if (!sd) return v2_undef();
    sd->pcm = (s16*)malloc((size_t)(samples ? samples : 1) * ch * sizeof(s16));
    if (!sd->pcm) { free(sd); return v2_undef(); }
    for (i = 0; i < samples; i++) for (k = 0; k < ch; k++) {
        const u8 *p = ba->bytes + ba->bpos; double v; ba->bpos += bps;
        if (is_float) { u32 u = ba->ival ? (u32)p[0] | ((u32)p[1] << 8) | ((u32)p[2] << 16) | ((u32)p[3] << 24) : ((u32)p[0] << 24) | ((u32)p[1] << 16) | ((u32)p[2] << 8) | p[3]; float fv; memcpy(&fv, &u, 4); v = fv * 32768.0; }
        else v = (s16)(ba->ival ? (p[0] | (p[1] << 8)) : ((p[0] << 8) | p[1]));
        if (v > 32767) v = 32767; if (v < -32768) v = -32768; if (v != v) v = 0;
        sd->pcm[i * ch + k] = (s16)v;
    }
    sd->nframes = (int)samples; sd->rate = (int)rate; sd->stereo = stereo; sd->format = 3;
    sd->hdr_rate = sd->rate; sd->hdr_count = samples;
    s->bytes_total = samples * (u32)(bps * ch);
    set_sound(vm, o, s, sd, 1);
    return v2_undef();
}

