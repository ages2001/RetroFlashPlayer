/* computeSpectrum (Ruffle's sound_mixer.rs): the last 512 output frames, raw or
 * as a 2048-point FFT of them (real part, ln|x|/4), stretched */
static V2 sm_computeSpectrum(VM2 *vm, V2 self, int argc, V2 *argv) {
    extern int a2_ba_write_u32(VM2 *vm, A2Obj *b, u32 v);
    static float hist[1024 * 2]; static double cosv[2048]; static int cos_ok;
    A2Obj *ba; int fft = argc > 1 && BOOL(1), stretch = argc > 2 ? INT(2) : 0, i, ch, repeats, written;
    (void)self;
    if (ARG(0).t != T_OBJ || ARG(0).u.o->kind != OK_BYTEARRAY) { a2_throw_error(vm, "TypeError", "Error #2007: Parameter outputArray must be non-null.", 2007); return v2_undef(); }
    ba = ARG(0).u.o;
    audio_sample_history(vm->player, hist);
    if (fft) {
        static float out[512 * 2];
        if (!cos_ok) { for (i = 0; i < 2048; i++) cosv[i] = cos(2.0 * 3.14159265358979323846 * i / 2048.0); cos_ok = 1; }
        for (ch = 0; ch < 2; ch++) {
            int k, n;
            for (k = 0; k < 512; k++) {
                double re = 0;
                for (n = 0; n < 512; n++) re += hist[n * 2 + ch] * cosv[(k * n) & 2047];
                re = fabs(re);
                out[k * 2 + ch] = re > 0 ? (float)(log(re) > 0 ? log(re) / 4.0 : 0) : 0;
            }
        }
        memcpy(hist, out, sizeof(out));
    }
    if (stretch == 0) for (i = 0; i < 256; i++) { hist[i * 2] = hist[i * 4]; hist[i * 2 + 1] = hist[i * 4 + 1]; }
    repeats = stretch - 1 < 1 ? 1 : stretch - 1;
    ba->bpos = 0;
    for (ch = 0; ch < 2; ch++) {
        written = 0;
        for (i = 0; i < 256 && written < 256; i++) {
            int r;
            for (r = 0; r < repeats && written < 256; r++) { u32 u; memcpy(&u, &hist[i * 2 + ch], 4); if (!a2_ba_write_u32(vm, ba, u)) return v2_undef(); written++; }
        }
    }
    if (ba->blen > 2048) ba->blen = 2048;
    ba->bpos = 0;
    return v2_undef();
}

