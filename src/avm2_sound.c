static A2Sound *snd_of(A2Obj *o) {
    if (!o || o->kind != OK_SOUND) return NULL;
    if (!o->payload) { A2Sound *s = (A2Sound*)calloc(1, sizeof(A2Sound)); o->payload = s; }
    return (A2Sound*)o->payload;
}
static A2Chan *chan_of(A2Obj *o) {
    if (!o || o->kind != OK_SOUNDCHANNEL) return NULL;
    if (!o->payload) { A2Chan *c = (A2Chan*)calloc(1, sizeof(A2Chan)); if (c) memcpy(c->st, st_def, sizeof(c->st)); o->payload = c; }
    return (A2Chan*)o->payload;
}
void a2_sound_free_payload(A2Obj *o) {
    A2Sound *s = (A2Sound*)o->payload;
    if (s && s->owns_sd && s->sd) sound_def_free(s->sd);
    free(s); o->payload = NULL;
}

/* hidden arrays on the global object (they also keep their members alive) */
static A2Obj *glist(VM2 *vm, const char *name) {
    V2 q = hget(vm, vm->global, name);
    if (q.t != T_OBJ) { q = v2_obj(a2_new_array(vm)); hset(vm, vm->global, name, q); }
    return q.u.o;
}
static void glist_add(VM2 *vm, const char *name, A2Obj *o) {
    A2Obj *q = glist(vm, name); u32 i, n = a2_arr_len(q);
    for (i = 0; i < n; i++) { V2 v = a2_arr_get(q, (int)i); if (v.t == T_OBJ && v.u.o == o) return; }
    a2_arr_push(vm, q, v2_obj(o));
}
static void glist_remove(VM2 *vm, const char *name, A2Obj *o) {
    A2Obj *q = glist(vm, name); u32 i, n = a2_arr_len(q), k = 0;
    for (i = 0; i < n; i++) { V2 v = a2_arr_get(q, (int)i); if (v.t == T_OBJ && v.u.o == o) continue; a2_arr_set(vm, q, (int)k++, v); }
    if (k != n) a2_arr_setlen(vm, q, (int)k);
}
/* a snapshot of a list (dispatching may change it) */
static int glist_snapshot(VM2 *vm, const char *name, A2Obj ***out) {
    A2Obj *q = glist(vm, name); u32 i, n = a2_arr_len(q); A2Obj **a; int k = 0;
    *out = NULL;
    if (!n) return 0;
    a = (A2Obj**)malloc(n * sizeof(A2Obj*));
    if (!a) return 0;
    for (i = 0; i < n; i++) { V2 v = a2_arr_get(q, (int)i); if (v.t == T_OBJ) a[k++] = v.u.o; }
    *out = a;
    return k;
}

static void fire(VM2 *vm, A2Obj *t, const char *type) { a2_dispatch_simple(vm, t, a2_str(vm, type), 0); if (vm->throwing) a2_report_uncaught(vm); }
static void fire_progress(VM2 *vm, A2Obj *t, u32 loaded, u32 total) {
    A2Class *pc = a2_class_find_s(vm, "flash.events::ProgressEvent"); V2 a[5], e;
    a[0] = v2_cstr(vm, "progress"); a[1] = v2_bool(0); a[2] = v2_bool(0); a[3] = v2_num(loaded); a[4] = v2_num(total);
    e = a2_construct_class(vm, pc, 5, a);
    if (e.t == T_OBJ) a2_dispatch_event_obj(vm, t, e.u.o);
    if (vm->throwing) a2_report_uncaught(vm);
}
static void fire_ioerror(VM2 *vm, A2Obj *t, const char *msg, int id) {
    A2Class *ioe = a2_class_find_s(vm, "flash.events::IOErrorEvent"); A2Obj *e;
    if (!a2_has_listener(t, a2_str(vm, "ioError"))) { if (vm->player->debug) fprintf(stderr, "Error #2044: Unhandled IOErrorEvent:. text=%s\n", msg); return; }
    e = a2_make_event(vm, ioe, a2_str(vm, "ioError"), 0, 0);
    a2_dyn_set(vm, e, a2_str(vm, "text"), v2_cstr(vm, msg)); a2_dyn_set(vm, e, a2_str(vm, "errorID"), v2_int(id));
    a2_dispatch_event_obj(vm, t, e);
    if (vm->throwing) a2_report_uncaught(vm);
}

