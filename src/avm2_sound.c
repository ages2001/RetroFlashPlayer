/* extract: float stereo 44.1 kHz samples, linear interpolation from the sound's rate */
static V2 snd_extract(VM2 *vm, V2 self, int argc, V2 *argv) {
    extern int a2_ba_write_u32(VM2 *vm, A2Obj *b, u32 v);
    A2Sound *s = snd_of(SELFO); A2Obj *ba; double len, startp, start, total, i; SoundDef *sd; int nout = 0;
    if (ARG(0).t != T_OBJ || ARG(0).u.o->kind != OK_BYTEARRAY) { a2_throw_error(vm, "TypeError", "Error #2007: Parameter target must be non-null.", 2007); return v2_undef(); }
    ba = ARG(0).u.o; len = NUM(1); startp = argc > 2 ? NUM(2) : -1;
    if (!s || !s->sd || s->sd->nframes <= 0 || s->sd->rate <= 0) return v2_num(0);
    sd = s->sd;
    start = startp < 0 || startp != startp ? s->extract_pos : floor(startp);
    total = floor((double)sd->nframes * AUDIO_RATE / sd->rate);
    if (!(len > 0)) return v2_num(0);
    for (i = 0; i < len && start + i < total; i++) {
        double sp = (start + i) * sd->rate / AUDIO_RATE; int i0 = (int)sp, i1 = i0 + 1, k; double fr = sp - i0;
        if (i1 >= sd->nframes) i1 = sd->nframes - 1;
        for (k = 0; k < 2; k++) {
            double a0 = sd->stereo ? sd->pcm[i0 * 2 + k] : sd->pcm[i0], a1 = sd->stereo ? sd->pcm[i1 * 2 + k] : sd->pcm[i1];
            float f = (float)((a0 + (a1 - a0) * fr) / 32768.0); u32 u;
            memcpy(&u, &f, 4);
            if (!a2_ba_write_u32(vm, ba, u)) return v2_undef();
        }
        nout++;
    }
    s->extract_pos = start + nout;
    return v2_num(nout);
}

