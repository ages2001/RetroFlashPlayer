/* ID3 (v2.2-2.4, else v1)                                           */

typedef struct { char *buf; size_t n, cap; } SB;
static void sb_byte(SB *b, int c) { if (b->n + 2 > b->cap) { size_t nc = b->cap ? b->cap * 2 : 64; char *nb = (char*)realloc(b->buf, nc); if (!nb) return; b->buf = nb; b->cap = nc; } b->buf[b->n++] = (char)c; b->buf[b->n] = 0; }
static void sb_cp(SB *b, u32 c) {
    if (c < 0x80) sb_byte(b, (int)c);
    else if (c < 0x800) { sb_byte(b, 0xC0 | (c >> 6)); sb_byte(b, 0x80 | (c & 63)); }
    else if (c < 0x10000) { sb_byte(b, 0xE0 | (c >> 12)); sb_byte(b, 0x80 | ((c >> 6) & 63)); sb_byte(b, 0x80 | (c & 63)); }
    else { sb_byte(b, 0xF0 | (c >> 18)); sb_byte(b, 0x80 | ((c >> 12) & 63)); sb_byte(b, 0x80 | ((c >> 6) & 63)); sb_byte(b, 0x80 | (c & 63)); }
}
static V2 id3_text(VM2 *vm, int enc, const u8 *p, size_t n) {
    SB b; size_t i; V2 r;
    memset(&b, 0, sizeof(b)); sb_byte(&b, 0); b.n = 0;
    if (enc == 0) { for (i = 0; i < n && p[i]; i++) sb_cp(&b, p[i]); }
    else if (enc == 3) { for (i = 0; i < n && p[i]; i++) sb_byte(&b, p[i]); }
    else {
        int be = enc == 2;
        if (enc == 1 && n >= 2) { if (p[0] == 0xFF && p[1] == 0xFE) { be = 0; p += 2; n -= 2; } else if (p[0] == 0xFE && p[1] == 0xFF) { be = 1; p += 2; n -= 2; } }
        for (i = 0; i + 1 < n; i += 2) {
            u32 c = be ? (u32)((p[i] << 8) | p[i + 1]) : (u32)(p[i] | (p[i + 1] << 8));
            if (!c) break;
            if (c >= 0xD800 && c < 0xDC00 && i + 3 < n) { u32 d = be ? (u32)((p[i + 2] << 8) | p[i + 3]) : (u32)(p[i + 2] | (p[i + 3] << 8)); if (d >= 0xDC00 && d < 0xE000) { c = 0x10000 + ((c - 0xD800) << 10) + (d - 0xDC00); i += 2; } }
            sb_cp(&b, c);
        }
    }
    r = v2_str(a2_intern(vm, b.buf ? b.buf : "", b.n));
    free(b.buf);
    return r;
}
static size_t id3_skip(int enc, const u8 *p, size_t n) {
    size_t i;
    if (enc == 0 || enc == 3) { for (i = 0; i < n; i++) if (!p[i]) return i + 1; return n; }
    for (i = 0; i + 1 < n; i += 2) if (!p[i] && !p[i + 1]) return i + 2;
    return n;
}
static const char *id3_v22(const char *id) {
    static const char *map[][2] = { { "TT2", "TIT2" }, { "TP1", "TPE1" }, { "TAL", "TALB" }, { "TRK", "TRCK" }, { "TYE", "TYER" }, { "TCO", "TCON" }, { "COM", "COMM" },
        { "TT1", "TIT1" }, { "TT3", "TIT3" }, { "TP2", "TPE2" }, { "TP3", "TPE3" }, { "TP4", "TPE4" }, { "TCM", "TCOM" }, { "TXT", "TEXT" }, { "TLA", "TLAN" },
        { "TBP", "TBPM" }, { "TCR", "TCOP" }, { "TDA", "TDAT" }, { "TEN", "TENC" }, { "TIM", "TIME" }, { "TLE", "TLEN" }, { "TPA", "TPOS" }, { "TPB", "TPUB" }, { NULL, NULL } };
    int i;
    for (i = 0; map[i][0]; i++) if (!strcmp(map[i][0], id)) return map[i][1];
    return NULL;
}
static void id3_setnum(VM2 *vm, V2 id3, const char *key, V2 text) {
    /* track / year are numbers to the id3 crate: "5/12" is track 5, "2009-03-01" year 2009 */
    const char *s = text.t == T_STR ? text.u.s->s : ""; long v = 0; int neg = 0, any = 0; char b[32];
    while (*s == ' ') s++;
    if (*s == '-') { neg = 1; s++; }
    while (*s >= '0' && *s <= '9' && v < 100000000L) { v = v * 10 + (*s - '0'); s++; any = 1; }
    if (!any) return;
    sprintf(b, "%ld", neg ? -v : v);
    a2_set_s(vm, id3, key, v2_cstr(vm, b));
}
/* returns whether a tag was found (the id3 event is sent then) */
static int parse_id3(VM2 *vm, V2 id3, const u8 *d, size_t n) {
    int ver, flags, have_comm = 0, have_year = 0; size_t size, pos, end; u8 *buf = NULL; const u8 *t;
    if (n >= 10 && !memcmp(d, "ID3", 3) && d[3] >= 2 && d[3] <= 4) {
        ver = d[3]; flags = d[5];
        size = ((size_t)(d[6] & 0x7F) << 21) | ((size_t)(d[7] & 0x7F) << 14) | ((size_t)(d[8] & 0x7F) << 7) | (d[9] & 0x7F);
        if (size + 10 > n) size = n - 10;
        t = d + 10;
        if (flags & 0x80 && ver < 4) {      /* unsynchronisation (whole tag) */
            size_t i, o = 0;
            buf = (u8*)malloc(size ? size : 1);
            if (!buf) return 0;
            for (i = 0; i < size; i++) { buf[o++] = t[i]; if (t[i] == 0xFF && i + 1 < size && t[i + 1] == 0) i++; }
            t = buf; size = o;
        }
        pos = 0; end = size;
        if (flags & 0x40 && ver >= 3 && size >= 4) pos = ver == 3 ? (((size_t)t[0] << 24) | ((size_t)t[1] << 16) | ((size_t)t[2] << 8) | t[3]) + 4 : ((size_t)(t[0] & 0x7F) << 21) | ((size_t)(t[1] & 0x7F) << 14) | ((size_t)(t[2] & 0x7F) << 7) | (t[3] & 0x7F);
        while (pos + (ver == 2 ? 6 : 10) <= end) {
            char id[5]; const char *fid; size_t fs; int fflags = 0, enc; const u8 *f; V2 v;
            if (ver == 2) { memcpy(id, t + pos, 3); id[3] = 0; fs = ((size_t)t[pos + 3] << 16) | ((size_t)t[pos + 4] << 8) | t[pos + 5]; pos += 6; }
            else {
                memcpy(id, t + pos, 4); id[4] = 0;
                if (ver == 4) fs = ((size_t)(t[pos + 4] & 0x7F) << 21) | ((size_t)(t[pos + 5] & 0x7F) << 14) | ((size_t)(t[pos + 6] & 0x7F) << 7) | (t[pos + 7] & 0x7F);
                else fs = ((size_t)t[pos + 4] << 24) | ((size_t)t[pos + 5] << 16) | ((size_t)t[pos + 6] << 8) | t[pos + 7];
                fflags = (t[pos + 8] << 8) | t[pos + 9];
                pos += 10;
            }
            if (!id[0] || fs > end - pos) break;
            f = t + pos; pos += fs;
            fid = ver == 2 ? id3_v22(id) : id;
            if (!fid || !fs) continue;
            if (ver == 3 && (fflags & 0x00C0)) continue;
            if (ver == 4 && (fflags & 0x000C)) continue;
            enc = f[0];
            if (!strcmp(fid, "COMM")) {
                size_t p2;
                if (fs < 4) continue;
                p2 = 4 + id3_skip(enc, f + 4, fs - 4);
                v = id3_text(vm, enc, f + (p2 < fs ? p2 : fs), p2 < fs ? fs - p2 : 0);
                if (!have_comm) { a2_set_s(vm, id3, "comment", v); have_comm = 1; }
                a2_set_s(vm, id3, fid, v);
            } else if (fid[0] == 'T' && strcmp(fid, "TXXX")) {
                v = id3_text(vm, enc, f + 1, fs - 1);
                if (!strcmp(fid, "TALB")) a2_set_s(vm, id3, "album", v);
                else if (!strcmp(fid, "TCON")) a2_set_s(vm, id3, "genre", v);
                else if (!strcmp(fid, "TIT2")) a2_set_s(vm, id3, "songName", v);
                else if (!strcmp(fid, "TPE1")) a2_set_s(vm, id3, "artist", v);
                else if (!strcmp(fid, "TRCK")) id3_setnum(vm, id3, "track", v);
                else if (!strcmp(fid, "TYER")) { id3_setnum(vm, id3, "year", v); have_year = 1; }
                else if (!strcmp(fid, "TDRC") && !have_year) id3_setnum(vm, id3, "year", v);
                a2_set_s(vm, id3, fid, v);
            }
            if (vm->throwing) { vm->throwing = 0; vm->exc = v2_undef(); }
        }
        free(buf);
        return 1;
    }
    if (n >= 128 && !memcmp(d + n - 128, "TAG", 3)) {   /* ID3v1 / v1.1 */
        const u8 *g = d + n - 128; char b[16];
        a2_set_s(vm, id3, "songName", id3_text(vm, 0, g + 3, 30));
        a2_set_s(vm, id3, "artist", id3_text(vm, 0, g + 33, 30));
        a2_set_s(vm, id3, "album", id3_text(vm, 0, g + 63, 30));
        a2_set_s(vm, id3, "year", id3_text(vm, 0, g + 93, 4));
        a2_set_s(vm, id3, "comment", id3_text(vm, 0, g + 97, 30));
        if (!g[125] && g[126]) { sprintf(b, "%d", g[126]); a2_set_s(vm, id3, "track", v2_cstr(vm, b)); }
        if (g[127] != 255) { sprintf(b, "%d", g[127]); a2_set_s(vm, id3, "genre", v2_cstr(vm, b)); }
        if (vm->throwing) { vm->throwing = 0; vm->exc = v2_undef(); }
        return 1;
    }
    return 0;
}
/* Sound::read_and_call_id3_event: the sound gets an ID3Info; the event only for a tag */
static void read_id3(VM2 *vm, A2Obj *o, const u8 *d, size_t n) {
    A2Class *ic = a2_class_find_s(vm, "flash.media::ID3Info"); V2 id3; int tag;
    id3 = ic ? a2_construct_class(vm, ic, 0, NULL) : v2_obj(a2_new_plain(vm));
    if (vm->throwing) { a2_report_uncaught(vm); return; }
    tag = parse_id3(vm, id3, d, n);
    hset(vm, o, "__id3", id3);
    if (tag) fire(vm, o, "id3");
}

