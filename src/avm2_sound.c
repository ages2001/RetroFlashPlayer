/* generated sound: keep about a few frames of samples queued */
static void dyn_feed(VM2 *vm, A2Obj *cho, A2Chan *c) {
    A2Class *sde = a2_class_find_s(vm, "flash.events::SampleDataEvent");
    double fr = vm->player->movie && vm->player->movie->framerate > 0 ? vm->player->movie->framerate : 12.0;
    int target = (int)(AUDIO_RATE / fr) * 3, guard;
    if (target < 8192) target = 8192;
    for (guard = 0; guard < 16 && c->state == CH_DYNAMIC && !c->dyn_ended; guard++) {
        int have = audio_dyn_buffered(vm->player, c->inst), n, k; V2 a[5], e; A2Obj *ba; s16 *pcm;
        if (have < 0) break;
        if (have >= target) break;
        ba = a2_new(vm, vm->c_bytearray); ba->kind = OK_BYTEARRAY;
        a[0] = v2_cstr(vm, "sampleData"); a[1] = v2_bool(0); a[2] = v2_bool(0); a[3] = v2_num(c->dyn_samples); a[4] = v2_obj(ba);
        e = sde ? a2_construct_class(vm, sde, 5, a) : v2_undef();
        if (e.t == T_OBJ) a2_dispatch_event_obj(vm, c->sound, e.u.o);
        if (vm->throwing) a2_report_uncaught(vm);
        if (c->state != CH_DYNAMIC || !c->inst) break;   /* stopped by the listener */
        n = ba->blen / 8;
        if (n > 0 && (pcm = (s16*)malloc((size_t)n * 2 * sizeof(s16))) != NULL) {
            for (k = 0; k < n * 2; k++) {
                const u8 *p = ba->bytes + k * 4; u32 u = ba->ival ? (u32)p[0] | ((u32)p[1] << 8) | ((u32)p[2] << 16) | ((u32)p[3] << 24) : ((u32)p[0] << 24) | ((u32)p[1] << 16) | ((u32)p[2] << 8) | p[3];
                float f; double v; memcpy(&f, &u, 4); v = f * 32768.0;
                if (v != v) v = 0; if (v > 32767) v = 32767; if (v < -32768) v = -32768;
                pcm[k] = (s16)v;
            }
            audio_dyn_push(vm->player, c->inst, pcm, n);
            free(pcm);
        }
        c->dyn_samples += n;
        if (n < 2048) { audio_dyn_end(vm->player, c->inst); c->dyn_ended = 1; break; }
    }
}

void a2_sound_frame(VM2 *vm) {
    A2Obj **items, *done[64]; int n, i, nd = 0, inst;
    /* sounds that played to their end */
    audio_avm2_complete_ahead(vm->player, 2048);
    while (audio_take_done2(vm->player, &inst)) {
        A2Obj *q = glist(vm, "__sndch"); u32 k, m = a2_arr_len(q);
        for (k = 0; k < m; k++) {
            V2 v = a2_arr_get(q, (int)k); A2Chan *c = v.t == T_OBJ ? chan_of(v.u.o) : NULL;
            if (!c || c->inst != inst) continue;
            c->pos = c->state == CH_DYNAMIC ? c->dyn_samples * 1000.0 / AUDIO_RATE : sound_length_ms(snd_of(c->sound));
            c->inst = 0; c->state = CH_DONE;
            glist_remove(vm, "__sndch", v.u.o);
            if (nd < 64) done[nd++] = v.u.o;
            break;
        }
    }
    if (nd) {
        A2Obj *keep = a2_new_array(vm);   /* reachable while their events run */
        hset(vm, vm->global, "__sndDone", v2_obj(keep));
        for (i = 0; i < nd; i++) a2_arr_push(vm, keep, v2_obj(done[i]));
        for (i = 0; i < nd; i++) { a2_dispatch_simple(vm, done[i], vm->s_soundComplete, 0); if (vm->throwing) a2_report_uncaught(vm); }
        hset(vm, vm->global, "__sndDone", v2_undef());
    }
    apply_transforms(vm);
    /* queued plays of sounds without data that have sampleData listeners become generated sounds */
    n = glist_snapshot(vm, "__sndch", &items);
    for (i = 0; i < n; i++) {
        A2Chan *c = chan_of(items[i]); A2Sound *s;
        if (!c) continue;
        s = snd_of(c->sound);
        if (c->state == CH_QUEUED && s && s->state == SS_NEW && a2_has_listener(c->sound, a2_str(vm, "sampleData"))) {
            c->inst = audio_dyn_start(vm->player, items[i]);
            if (!c->inst) { c->state = CH_IDLE; glist_remove(vm, "__sndch", items[i]); continue; }
            c->state = CH_DYNAMIC; c->dyn_samples = 0; c->dyn_ended = 0;
            chan_apply_st(vm, c);
        }
        if (c->state == CH_DYNAMIC && c->inst) dyn_feed(vm, items[i], c);
    }
    free(items);
    process_loads(vm);
}

