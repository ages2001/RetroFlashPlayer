enum { SS_NEW, SS_LOADING, SS_LOADED };

typedef struct A2Sound {
    int state;
    SoundDef *sd;           /* NULL until loaded */
    int owns_sd;            /* decoded from loaded bytes: freed with the object */
    u32 bytes_total;        /* compressed size (Ruffle: get_sound_size) */
    int req_frame;          /* frame load() was called in */
    int cancelled;          /* close() during the load */
    double extract_pos;     /* next sample (44.1 kHz) extract() reads with startPosition -1 */
} A2Sound;

typedef struct A2Chan {
    A2Obj *sound;           /* kept alive through the hidden __sound property */
    int inst;               /* mixer voice, 0 when none */
    int state;              /* CH_* */
    int st[5];              /* volume, ll, lr, rl, rr in percent */
    double start_ms;        /* startTime of play() */
    int loops;
    double pos;             /* cached position (ms) */
    double dyn_samples;     /* dynamic: samples requested so far (SampleDataEvent.position) */
    int dyn_ended;          /* dynamic: a short answer ended the data */
} A2Chan;
enum { CH_IDLE, CH_QUEUED, CH_PLAYING, CH_DYNAMIC, CH_DONE };

