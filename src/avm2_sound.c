static V2 snd_play(VM2 *vm, V2 self, int argc, V2 *argv) {
    A2Obj *o = SELFO, *cho; A2Sound *s = snd_of(o); A2Chan *c; double start = argc > 0 ? NUM(0) : 0; int loops = argc > 1 ? INT(1) : 0;
    if (!s) return v2_null();
    if (vm->throwing) return v2_undef();
    if (start != start) start = 0;
    if (s->sd && start > sound_length_ms(s)) return v2_null();   /* past the end: no channel */
    cho = a2_new(vm, vm->c_soundchannel); cho->kind = OK_SOUNDCHANNEL;
    c = chan_of(cho);
    if (!c) return v2_null();
    c->sound = o; c->start_ms = start > 0 ? start : 0; c->loops = loops < 1 ? 1 : loops;
    hset(vm, cho, "__sound", self);
    if (ARG(2).t == T_OBJ) st_to_ints(vm, ARG(2), c->st);
    if (s->sd) { chan_start(vm, cho, c, s->sd); return v2_obj(cho); }
    /* no data yet: the play waits for it (or for sampleData listeners at the end of the frame) */
    {
        V2 q = hget(vm, o, "__queued");
        if (q.t != T_OBJ) { q = v2_obj(a2_new_array(vm)); hset(vm, o, "__queued", q); }
        if (a2_arr_len(q.u.o) >= 32) return v2_null();   /* AudioManager::MAX_SOUNDS */
        a2_arr_push(vm, q.u.o, v2_obj(cho));
    }
    c->state = CH_QUEUED;
    glist_add(vm, "__sndch", cho);
    return v2_obj(cho);
}

