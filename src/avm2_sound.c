/* avm2_sound.c - flash.media: Sound, SoundChannel, SoundMixer, SoundTransform,
 * ID3Info and SoundLoaderContext (AVM2).
 *
 * Follows Flash Player 10 and Ruffle (core/src/avm2/globals/flash/media,
 * avm2/object/sound_object.rs, soundchannel_object.rs, backend/audio.rs):
 *   - a Sound holds a decoded SoundDef: the DefineSound of its symbol class,
 *     an MP3 file (load), MP3 or PCM bytes from a ByteArray;
 *   - load() fetches at the end of the frame it was called in and then fires
 *     open, progress, id3 (when the file has a tag) and complete; plays asked
 *     for before the data arrived start then;
 *   - every play() gets its own SoundChannel (its own mixer voice) with its own
 *     transform; SoundMixer.soundTransform is applied on top of it;
 *   - a Sound without data but with a sampleData listener is generated by the
 *     script: SampleDataEvents pull 2048..8192 stereo float samples at a time,
 *     fewer than 2048 end the sound;
 *   - soundComplete is sent at the end of the frame the sound ended in. */
