#!/usr/bin/env python3
"""Turn the DoAction tags of a compiled playerglobal SWF into a C array.

Each DoAction body is stored as a little-endian u32 length followed by
the action bytes (see run_playerglobal in src/avm1_globals.c)."""
import struct, sys, zlib

def tags(data):
    if data[:3] == b'CWS':
        data = data[:8] + zlib.decompress(data[8:])
    pos = 8
    nbits = data[pos] >> 3
    pos += (5 + nbits * 4 + 7) // 8 + 4
    while pos + 2 <= len(data):
        code_len, = struct.unpack_from('<H', data, pos); pos += 2
        code, length = code_len >> 6, code_len & 0x3F
        if length == 0x3F:
            length, = struct.unpack_from('<I', data, pos); pos += 4
        yield code, data[pos:pos + length]
        pos += length
        if code == 0:
            break

def main():
    data = open(sys.argv[1], 'rb').read()
    blob = b''
    for code, body in tags(data):
        if code == 12:
            blob += struct.pack('<I', len(body)) + body
    print('/* avm1_playerglobal.c - generated by tools/gen_playerglobal.py from')
    print(' * the ActionScript in tools/playerglobal_avm1: do not edit. */')
    print('const unsigned char avm1_playerglobal[] = {')
    for i in range(0, len(blob), 16):
        print('    ' + ''.join('%d,' % b for b in blob[i:i + 16]))
    print('    0 };')
    print('const unsigned long avm1_playerglobal_len = %dUL;' % len(blob))

main()
