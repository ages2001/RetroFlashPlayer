#!/usr/bin/env python3
"""bin2c.py file name: a C89 byte array (and its length) for a binary file."""
import sys
data = open(sys.argv[1], 'rb').read(); name = sys.argv[2]
out = ['/* generated by tools/bin2c.py - do not edit */', '#include "flashnt.h"', 'const u8 %s[%d] = {' % (name, max(len(data), 1))]
for i in range(0, len(data), 20):
    out.append('    ' + ','.join(str(b) for b in data[i:i + 20]) + ',')
out.append('};'); out.append('const unsigned long %s_len = %dUL;' % (name, len(data)))
print('\n'.join(out))
